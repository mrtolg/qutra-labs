/* ============================================================
   Engagement report generation (pure).

   Builds a Markdown report from verified finding + evidence records and a
   matching Report metadata row for the `reports` collection. No I/O here.
   ============================================================ */

import {
  REPORT_BODY_LIMIT,
  ReportSchema,
  type Confidence,
  type Evidence,
  type Finding,
  type FindingStatus,
  type Report,
  type Severity,
} from "@/domain/findings";
import type { Engagement } from "@/domain/lab";
import { sha256Hex } from "@/lib/hash";
import { createId } from "@/lib/id";

export { REPORT_BODY_LIMIT };

const SEVERITY_ORDER: Severity[] = [
  "critical",
  "high",
  "medium",
  "low",
  "info",
];

/** The report's own words, in the reader's language. */
export interface ReportWords {
  /** The heading: "<investigation> — report". */
  title: (engagement: string) => string;
  generated: string;
  executiveSummary: string;
  /** The summary when none is written. */
  summaryLine: (count: number, engagement: string) => string;
  /** The saved record's short summary. */
  recordSummary: (count: number) => string;
  severitySummary: string;
  findings: string;
  noFindings: string;
  severity: string;
  status: string;
  confidence: string;
  sourceTool: string;
  targets: string;
  location: string;
  impact: string;
  reproduction: string;
  remediation: string;
  evidence: string;
  withheld: string;
  footer: string;
  severityName: (severity: Severity) => string;
  statusName: (status: FindingStatus) => string;
  confidenceName: (confidence: Confidence) => string;
}

export const ENGLISH_WORDS: ReportWords = {
  title: (engagement) => `${engagement} — report`,
  generated: "Generated",
  executiveSummary: "Executive summary",
  summaryLine: (count, engagement) => `${count} finding(s) across ${engagement}.`,
  recordSummary: (count) => `${count} finding(s).`,
  severitySummary: "Severity summary",
  findings: "Findings",
  noFindings: "No findings included.",
  severity: "Severity",
  status: "Status",
  confidence: "Confidence",
  sourceTool: "Source tool",
  targets: "Targets",
  location: "Location",
  impact: "Impact",
  reproduction: "Reproduction",
  remediation: "Remediation",
  evidence: "Evidence",
  withheld: "content withheld: sensitive",
  footer: "Generated by Qutra Labs from local engagement data. Review before sharing.",
  severityName: (severity) => severity,
  statusName: (status) => status,
  confidenceName: (confidence) => confidence,
};

export interface ReportInput {
  engagement: Engagement;
  findings: readonly Finding[];
  evidence: readonly Evidence[];
  /** Optional operator summary; defaults to a short generated line. */
  executiveSummary?: string;
  now: number;
  title?: string;
  /** Name sensitive evidence without its content (default true). */
  withholdSensitive?: boolean;
  /** The report's own words (default English). */
  words?: ReportWords;
}

/** Text with its line endings as one LF (a lone CR ends a line too). */
function esc(text: string): string {
  return text.replace(/\r\n?/g, "\n").trim();
}

/* Text from tools and people goes into the report as text: a
   scan's output must not add an image a viewer would fetch, HTML, a link,
   a heading, a table or emphasis, or close a code block early. Markdown's
   marks are backslash-escaped, and &, < and > become entities, so the
   viewer shows exactly the characters the tool wrote. */
function escapeMarkup(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/[\\`[\]*_~|]/g, (c) => `\\${c}`);
}

/** One-line text: line breaks and runs of spaces become one space. */
function inline(text: string): string {
  return escapeMarkup(text.replace(/\s+/g, " ").trim());
}

/** Multi-line text: no line starts a heading, list, quote or rule, and each
    line break stays a line break (two trailing spaces), so steps and
    command lines keep their shape. */
function block(text: string): string {
  return esc(text)
    .split("\n")
    .map((line) =>
      escapeMarkup(line)
        .replace(/^(\s*)([-+=#])/, "$1\\$2")
        .replace(/^(\s*\d+)([.)])/, "$1\\$2"),
    )
    .join("  \n");
}

/** A fenced block its content cannot close: the fence is one backtick
    longer than the longest run inside. */
function fence(content: string): string {
  const longest = Math.max(0, ...(content.match(/`+/g) ?? []).map((run) => run.length));
  const ticks = "`".repeat(Math.max(3, longest + 1));
  return `${ticks}\n${content}\n${ticks}`;
}

function findingBlock(
  finding: Finding,
  evidence: readonly Evidence[],
  withholdSensitive: boolean,
  w: ReportWords,
): string {
  const linked = evidence.filter(
    (item) =>
      item.findingId === finding.id ||
      finding.evidenceIds.includes(item.id),
  );
  // Optional lines are null, so the blank line that ends the list stays:
  // without it the description would continue the last list item.
  const lines = [
    `### ${inline(finding.title)}`,
    "",
    `- **${w.severity}:** ${w.severityName(finding.severity)}`,
    `- **${w.status}:** ${w.statusName(finding.status)}`,
    `- **${w.confidence}:** ${w.confidenceName(finding.confidence)}`,
    finding.sourceTool ? `- **${w.sourceTool}:** ${inline(finding.sourceTool)}` : null,
    finding.affectedTargets.length
      ? `- **${w.targets}:** ${finding.affectedTargets.map(inline).join(", ")}`
      : null,
    finding.location ? `- **${w.location}:** ${inline(finding.location)}` : null,
    "",
  ].filter((line): line is string => line !== null);

  if (finding.description.trim()) {
    lines.push(block(finding.description), "");
  }
  if (finding.impact.trim()) {
    lines.push(`**${w.impact}**`, "", block(finding.impact), "");
  }
  if (finding.reproduction.trim()) {
    lines.push(`**${w.reproduction}**`, "", block(finding.reproduction), "");
  }
  if (finding.remediation.trim()) {
    lines.push(`**${w.remediation}**`, "", block(finding.remediation), "");
  }
  if (linked.length > 0) {
    lines.push(`**${w.evidence}**`, "");
    for (const item of linked) {
      if (!item.includeInReport) continue;
      // What could point at a person (a photo's location, owner, serial)
      // is named, not shown; not even its hash, which a guess could match.
      const withheld = item.sensitivity === "sensitive" && withholdSensitive;
      const hash = item.sha256 && !withheld ? ` · SHA-256 ${item.sha256.slice(0, 12)}…` : "";
      const body = withheld
        ? ` — _${w.withheld}_`
        : item.content.trim()
          ? `\n\n${fence(esc(item.content).slice(0, 4000))}`
          : item.path
            ? ` — ${inline(item.path)}`
            : "";
      lines.push(`- ${inline(item.title)} (${item.kind})${hash}${body}`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

/** Render a Markdown report body from engagement findings and evidence. */
export function buildMarkdownReport(input: ReportInput): string {
  const findings = [...input.findings].sort(
    (a, b) =>
      SEVERITY_ORDER.indexOf(a.severity) - SEVERITY_ORDER.indexOf(b.severity) ||
      b.updatedAt - a.updatedAt,
  );
  const counts = Object.fromEntries(
    SEVERITY_ORDER.map((severity) => [
      severity,
      findings.filter((f) => f.severity === severity).length,
    ]),
  ) as Record<Severity, number>;

  const w = input.words ?? ENGLISH_WORDS;
  const summary =
    block(input.executiveSummary ?? "") ||
    w.summaryLine(findings.length, inline(input.engagement.title));

  const sections = [
    `# ${inline(input.title ?? w.title(input.engagement.title))}`,
    "",
    `${w.generated}: ${new Date(input.now).toISOString()}`,
    "",
    `## ${w.executiveSummary}`,
    "",
    summary,
    "",
    `## ${w.severitySummary}`,
    "",
    ...SEVERITY_ORDER.map(
      (severity) => `- **${w.severityName(severity)}:** ${counts[severity]}`,
    ),
    "",
    `## ${w.findings}`,
    "",
  ];

  if (findings.length === 0) {
    sections.push(`_${w.noFindings}_`, "");
  } else {
    for (const finding of findings) {
      sections.push(findingBlock(finding, input.evidence, input.withholdSensitive ?? true, w));
    }
  }

  sections.push("---", "", `_${w.footer}_`, "");
  return sections.join("\n");
}

/**
 * Create a Report record linked to the engagement. `markdown` is the full
 * exported body: its SHA-256 is stored, and a bounded copy is kept on `body`.
 */
export async function createReportRecord(
  input: ReportInput,
  markdown: string,
): Promise<Report> {
  const w = input.words ?? ENGLISH_WORDS;
  const truncated = markdown.length > REPORT_BODY_LIMIT;
  const body = truncated
    ? `${markdown.slice(0, REPORT_BODY_LIMIT)}\n…[truncated]`
    : markdown;
  return ReportSchema.parse({
    id: createId("rpt"),
    engagementId: input.engagement.id,
    title: input.title ?? w.title(input.engagement.title),
    format: "markdown",
    includedFindingIds: input.findings.map((f) => f.id),
    executiveSummary:
      esc(input.executiveSummary ?? "") || w.recordSummary(input.findings.length),
    body,
    generatedAt: input.now,
    sha256: await sha256Hex(markdown),
    demo: false,
    createdAt: input.now,
    updatedAt: input.now,
  });
}

/** Filename-safe slug for a download. */
export function reportDownloadName(engagementTitle: string, at: number): string {
  const slug =
    engagementTitle
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
      .slice(0, 48) || "engagement";
  const day = new Date(at).toISOString().slice(0, 10);
  return `contextos-report-${slug}-${day}.md`;
}
