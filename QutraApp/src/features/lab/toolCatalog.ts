function normalizeToolIdentity(value: string): string {
  return value.toLocaleLowerCase("en-US").replace(/[^a-z0-9]+/g, "");
}

export function matchesToolInstallation(
  tool: Pick<ToolCatalogEntry, "id" | "name" | "repository">,
  installation: ToolInstallationIdentity,
): boolean {
  const repositoryName = tool.repository?.split("/").filter(Boolean).at(-1) ?? "";
  const candidates = [tool.id, tool.name, repositoryName]
    .map(normalizeToolIdentity)
    .filter((value) => value.length >= 3);
  const installedIdentities = [
    installation.displayName,
    installation.docUrl,
    ...installation.tags,
  ]
    .map(normalizeToolIdentity)
    .filter((value) => value.length >= 3);

  return candidates.some((candidate) =>
    installedIdentities.some(
      (identity) =>
        identity === candidate || identity.includes(candidate),
    ),
  );
}


